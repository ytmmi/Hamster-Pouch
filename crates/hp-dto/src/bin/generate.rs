//! 生成前端共享类型到 `packages/shared-types/src`（docs/spec/shared-types.md）。
//!
//! 用法：`cargo run -p hp-dto --bin generate -- [输出目录]`
//! 默认输出目录：相对本 crate 的 `../../packages/shared-types/src`。

use std::path::{Path, PathBuf};

use ts_rs::TS;

/// 需要生成的前端类型（与 `lib.rs` 中的 DTO 一一对应）。
fn export_all(out: &Path) {
    macro_rules! export {
        ($($t:ty),* $(,)?) => {{
            $(
                <$t as TS>::export_all_to(out)
                    .unwrap_or_else(|e| panic!("导出 {} 失败: {e}", stringify!($t)));
            )*
        }};
    }

    export!(
        hp_dto::RepoSummary,
        hp_dto::RepoListItem,
        hp_dto::SourceItem,
        hp_dto::AlbumFileItem,
        hp_dto::FileMetadataResult,
        hp_dto::PluginItem,
        hp_dto::DiscoveredPlugin,
        hp_dto::PluginStateItem,
        hp_dto::PluginLoadItem,
        hp_dto::AiConfigItem,
        hp_dto::AiTaskItem,
        hp_dto::AiRunSummary,
        hp_dto::FsOpsResult,
        hp_dto::TagItem,
        hp_dto::FileTagItem,
        hp_dto::FileTagsResult,
        hp_dto::TagRelationItem,
        hp_dto::BlueprintItem,
        hp_dto::BlueprintValidateResult,
        hp_dto::BlueprintTemplateItem,
        hp_dto::BookBlockItem,
        hp_dto::BookContentResult,
        hp_dto::BookCoverResult,
        hp_dto::BookCoverItem,
    );
}

/// 生成 barrel `index.ts`（统一重导出，供前端按域 import）。
fn write_index(out: &Path) {
    let names = [
        "RepoSummary",
        "RepoListItem",
        "SourceItem",
        "AlbumFileItem",
        "FileMetadataResult",
        "PluginItem",
        "DiscoveredPlugin",
        "PluginStateItem",
        "PluginLoadItem",
        "AiConfigItem",
        "AiTaskItem",
        "AiRunSummary",
        "FsOpsResult",
        "TagItem",
        "FileTagItem",
        "FileTagsResult",
        "TagRelationItem",
        "BlueprintItem",
        "BlueprintValidateResult",
        "BlueprintTemplateItem",
        "BookBlockItem",
        "BookContentResult",
        "BookCoverResult",
        "BookCoverItem",
    ];
    let mut content = String::from(
        "// @generated by hp-dto (ts-rs) — DO NOT EDIT\n\
         // source: crates/hp-dto/src/lib.rs\n\
         // regenerate: pnpm generate:types\n\n",
    );
    for name in names {
        content.push_str(&format!("export type {{ {name} }} from \"./{name}\";\n"));
    }
    std::fs::write(out.join("index.ts"), content).expect("写入 index.ts 失败");
}

fn main() {
    // 默认输出到本 crate 相对的 packages/shared-types/src（用绝对路径，避免
    // ts-rs 与 fs 对相对路径解析基准不一致）。
    let out = std::env::args().nth(1).map(PathBuf::from).unwrap_or_else(|| {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/shared-types/src")
    });
    std::fs::create_dir_all(&out).expect("创建输出目录失败");
    export_all(&out);
    write_index(&out);
    println!("已生成共享类型到 {}", out.display());
}
