-- 仓库库迁移 0016：被排除子树的「仅索引」标记。
-- forward-only：本文件发布后禁止修改。
--
-- 背景（2026-11-12 用户直接要求）：D149 的软排除只把子树从视图里隐藏，扫描器仍按全量
-- 口径处理它们——每张图照样解码、算内容哈希、出缩略图/预览、算感知哈希与调色板。
-- 用户口径改为：被排除的子树**只建索引**（相对路径 / 类型 / 体积 / mtime / 标记），
-- 不产任何衍生产物；已经被扫描过的子树在排除时还要把缩略图等大资源文件删掉。
--
-- 设计要点：
-- 1. 必须用显式列标记，不能靠 `content_hash IS NULL` 推断。读失败（unreadable）行的哈希
--    同样是 NULL——那是能力问题不是策略选择；音频占位行与历史行同理。用哈希空判会把
--    「被排除、衍生产物已删」和「读不出来」混成一件事，恢复后也无从判断谁该重建。
-- 2. 默认 0：既有行一律视为「完整索引」，行为与升级前逐字一致；只有排除收敛路径会写 1。
-- 3. 这一列**不进 `FILE_COLUMNS`**（`FileIndexRow` 仍是 20 列，相册分页等处的追加列
--    下标不动），只由扫描写回与排除清理两处按主键读写。
-- 4. 排除时只清**衍生产物列**（内容哈希 / 感知哈希 / `media_info_json` / `thumb_status`），
--    索引行、标记、评分、色彩参考、相册成员一行不删；`width` / `height` 也保留——回填
--    任务按 `width IS NULL` 挑行，清掉等于把被排除的文件排队去解码。
-- 5. 取消排除不自动扫：下一次扫描看到 `index_only = 1` 与「当前可见」不一致即强制重算，
--    写回 0 并重建缩略图——自愈而不是额外的后台任务。

ALTER TABLE files ADD COLUMN index_only INTEGER NOT NULL DEFAULT 0;
